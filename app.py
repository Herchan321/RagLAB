def _render_result(result: dict[str, Any]) -> None:
    with st.container(border=True, height="stretch"):
        st.subheader(SYSTEM_LABELS.get(result["system"], result["system"]))
        if result.get("execution_error"):
            st.error(result["execution_error"], icon=":material/error:")
        elif result.get("answer"):
            st.markdown(result["answer"])
        elif result["system"] in RETRIEVAL_ONLY:
            st.info("Retrieval only: no answer generated.")
        else:
            st.caption("No generated answer (generation is off).")

        metrics = result.get("retrieval_metrics")
        if metrics and result.get("fact_ids"):
            st.caption("Metrics on annotated question")
            metric_columns = st.columns(len(RANKING_METRICS))
            for column, (key, name) in zip(metric_columns, RANKING_METRICS.items()):
                column.metric(f"{name}@{DEFAULT_K}", f"{metrics.get(key, 0):.2f}")
        else:
            st.caption(
                f"{result.get('latency_ms', 0):.0f} ms · "
                f"{len(result.get('retrieved_passages', []))} passages retrieved"
            )

        with st.expander("View evidence"):
            passages = result.get("retrieved_passages", [])
            if not passages:
                st.caption("No passages retrieved.")
            for rank, passage in enumerate(passages, 1):
                score = passage.get("score")
                score_text = f" · score {score:.4f}" if score is not None else ""
                st.markdown(
                    f"**{rank}. {passage.get('article_id')} · "
                    f"{passage.get('chunk_id')}**{score_text}"
                )
                text = passage.get("text", "")
                st.caption(text[:300] + ("…" if len(text) > 300 else ""))
        if result.get("trace"):
            with st.expander("View technical trace"):
                st.json(result["trace"])


def _render_comparison(saved: dict[str, Any]) -> None:
    results = saved["results"]
    st.subheader("Results")
    st.caption(f"Question: {saved['question']}")
    if not saved["generated"]:
        st.info(
            "Generation is off: compare the retrieved evidence, not answers.",
            icon=":material/info:",
        )
    columns = st.columns(len(results), gap="medium")
    for column, result in zip(columns, results):
        with column:
            _render_result(result)

    st.subheader("Retrieval summary")
    st.dataframe(_comparison_summary(results), hide_index=True, width="stretch")
    st.caption(
        "Raw scores may use different scales per system (for example similarity "
        "versus rank fusion): compare ranks and passages, not values across systems."
    )


def _render_static_examples() -> None:
    st.divider()
    st.subheader("Example responses")
    st.caption(STATIC_EXAMPLE_NOTE)
    for example in STATIC_EXAMPLES:
        with st.expander(f"Q: {example['question']}"):
            st.markdown(example["answer"])


def _set_text(key: str, text: str) -> None:
    st.session_state[key] = text


def _example_buttons(key: str) -> None:
    st.caption("Try an example:")
    columns = st.columns(len(EXAMPLE_QUESTIONS))
    for column, (label, text) in zip(columns, EXAMPLE_QUESTIONS):
        column.button(
            label,
            key=f"{key}_{label}",
            on_click=_set_text,
            args=(key, text),
            width="stretch",
        )



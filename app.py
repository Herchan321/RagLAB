def _sidebar() -> bool:
    """Render the sidebar and return whether generation is active."""
    key_present = bool(os.getenv("GEMINI_API_KEY"))
    with st.sidebar:
        st.header("Settings")
        generate = st.toggle(
            "Enable Gemini generation", value=False, disabled=not key_present
        )
        if key_present:
            st.caption("Off by default to avoid API costs.")
        else:
            st.caption("No GEMINI_API_KEY found: retrieval-only demo.")
        st.info(
            "Answers are grounded in retrieved passages. "
            "They do not constitute legal advice.",
            icon=":material/info:",
        )
    return generate and key_present


def main() -> None:
    st.set_page_config(
        page_title="RAG Lab",
        page_icon=":material/compare_arrows:",
        layout="wide",
    )
    st.title("RAG Lab")
    st.caption("Comparing RAG architectures on the original AI Act 2024 text")

    generate = _sidebar()
    page = (
        st.segmented_control(
            "Navigation", PAGES, default="Compare", label_visibility="collapsed"
        )
        or "Compare"
    )

    if page == "Compare":
        page_compare(generate)
    elif page == "Assistant":
        page_assistant(generate)
    elif page == "Benchmark":
        page_benchmark()
    else:
        page_method()


if __name__ == "__main__":
    main()
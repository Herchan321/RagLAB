def page_compare(generate: bool) -> None:
    st.header("Compare systems")
    st.write("Ask a question and compare answers, evidence and timing.")
    _example_buttons("compare_question")

    with st.form("comparison_form"):
        question = st.text_area(
            "1. Your question",
            key="compare_question",
            placeholder="Ex. What obligations must deployers comply with under Article 26?",
            height=110,
        )
        selected = st.multiselect(
            "2. Systems to compare (maximum 3)",
            options=list(SYSTEMS),
            default=list(DEFAULT_SYSTEMS),
            format_func=lambda system: SYSTEM_LABELS.get(system, system),
            max_selections=3,
        )
        submitted = st.form_submit_button(
            "Run comparison", type="primary", width="stretch"
        )

    if submitted:
        text = question.strip()
        if not text:
            st.error("Enter a question.")
        elif not selected:
            st.error("Select at least one system.")
        else:
            with st.status("Retrieving passages and running systems…") as status:
                chunks, index, model = load_runtime()
                client = _make_client(generate)
                record = _question_record(text)
                results = [
                    run_system(
                        system, record, chunks, model, index, generator=client
                    )
                    for system in selected
                ]
                status.update(label="Comparison complete", state="complete")
            st.session_state["compare_results"] = {
                "question": text,
                "generated": client is not None,
                "results": results,
            }

    saved = st.session_state.get("compare_results")
    if saved:
        _render_comparison(saved)


def page_assistant(generate: bool) -> None:
    st.header("Assistant")
    st.write("Choose a single system and ask a question.")
    system = st.selectbox(
        "System",
        options=list(SYSTEMS),
        index=list(SYSTEMS).index("hybrid"),
        format_func=lambda value: SYSTEM_LABELS.get(value, value),
    )
    _example_buttons("assistant_question")

    with st.form("assistant_form"):
        question = st.text_area(
            "Question",
            key="assistant_question",
            placeholder="Ex. What is prohibited under Article 5?",
            height=110,
        )
        submitted = st.form_submit_button("Get answer", type="primary")

    if submitted:
        text = question.strip()
        if not text:
            st.error("Enter a question.")
        else:
            with st.status("Preparing response…") as status:
                chunks, index, model = load_runtime()
                client = _make_client(generate)
                result = run_system(
                    system,
                    _question_record(text),
                    chunks,
                    model,
                    index,
                    generator=client,
                )
                status.update(label="Response ready", state="complete")
            st.session_state["assistant_result"] = {
                "generated": client is not None,
                "result": result,
            }

    saved = st.session_state.get("assistant_result")
    if saved:
        if not saved["generated"]:
            st.warning(
                "Generation is off: showing retrieved passages only (read-only demo)."
            )
        _render_result(saved["result"])
        if not saved["generated"]:
            _render_static_examples()


def page_benchmark() -> None:
    st.header("Benchmark results")
    if not RESULTS_PATH.exists():
        st.info("Run the v3 dev benchmark first.")
        return

    payload = load_results(str(RESULTS_PATH), RESULTS_PATH.stat().st_mtime)
    systems = payload.get("systems", [])
    rows = payload.get("results", [])
    _, table, intervals, k = _aggregate(payload)

    summary = st.columns(3)
    summary[0].metric("Questions evaluated", str(len(rows) // max(len(systems), 1)))
    summary[1].metric("Systems compared", str(len(systems)))
    summary[2].metric(
        "Generation", "Enabled" if payload.get("generation_enabled") else "Disabled"
    )
    st.caption(
        "Dev split v3, not the final test set. Values are means with 95% bootstrap "
        "intervals over annotated questions; with so few questions the intervals "
        "are wide, so small differences between systems are not conclusive."
    )

    st.subheader("Per-system metrics")
    st.dataframe(table.reset_index(names="System"), hide_index=True, width="stretch")

    st.subheader(f"Metric comparison (k = {k})")
    st.altair_chart(_interval_chart(intervals))
    st.caption(
        "Dot = mean, bar = 95% bootstrap interval. Precision is omitted here "
        "(capped by the number of relevant anchors per question); see the table."
    )

    st.subheader("Paired differences")
    ranked = [s for s in systems if s != "no_retrieval"]
    baseline = st.selectbox(
        "Baseline",
        options=ranked,
        index=ranked.index("vector") if "vector" in ranked else 0,
        format_func=lambda value: SYSTEM_LABELS.get(value, value),
    )
    paired = _paired_differences(payload, baseline, k)
    if paired is None:
        st.info("Question ids not found in the results file: paired comparison unavailable.")
    else:
        st.dataframe(paired, hide_index=True, width="stretch")
        st.caption(
            "Question-by-question differences versus the baseline, on the same "
            "questions. An interval that excludes 0 indicates a consistent gain "
            "or loss on this sample; it does not generalise beyond it."
        )

    st.download_button(
        "Download JSON results",
        RESULTS_PATH.read_bytes(),
        file_name=RESULTS_PATH.name,
        mime="application/json",
        icon=":material/download:",
    )


def page_method() -> None:
    st.header("Method and limitations")
    st.markdown(
        """
        **Objective**

        Compare vector retrieval, BM25, hybrid, naive RAG and agentic RAG on the
        original text of the EU AI Act (Regulation (EU) 2024/1689).

        **Key points**

        - The v3 benchmark contains 55 questions: 26 in dev and 29 in test.
        - The test split is not yet frozen and has not been used for tuning.
        - Ranking metrics (recall, precision, MRR, nDCG) require questions annotated
          with text anchors; interactive questions have none, so no metric is shown.
        - Intervals are bootstrap estimates on a small sample; treat close results
          as ties.
        - This application does not provide legal advice.
        """
    )



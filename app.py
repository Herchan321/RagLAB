# --------------------------------------------------------------------------- #
# Aggregation helpers
# --------------------------------------------------------------------------- #
def _bootstrap_ci(
    values: list[float], n_boot: int = 2000, seed: int = 0
) -> tuple[float, float]:
    """95% percentile bootstrap interval of the mean (fixed seed, reproducible)."""
    array = np.asarray(values, dtype=float)
    if array.size < 2:
        return float("nan"), float("nan")
    rng = np.random.default_rng(seed)
    means = rng.choice(array, size=(n_boot, array.size), replace=True).mean(axis=1)
    low, high = np.percentile(means, [2.5, 97.5])
    return float(low), float(high)


def _format_mean_ci(mean: float, low: float, high: float) -> str:
    if np.isnan(low) or np.isnan(high):
        return f"{mean:.2f}"
    return f"{mean:.2f} [{low:.2f}–{high:.2f}]"


def _aggregate(
    payload: dict[str, Any],
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, int]:
    """Return (means, display table with 95% CIs, long-format intervals, k)."""
    rows = payload.get("results", [])
    k = int(payload.get("k", DEFAULT_K))
    columns = {f"{name}@{k}": key for key, name in RANKING_METRICS.items()}
    columns["Article coverage"] = COVERAGE_KEY

    numeric: dict[str, dict[str, float]] = {}
    display: dict[str, dict[str, Any]] = {}
    intervals: list[dict[str, Any]] = []
    for system in payload.get("systems", []):
        results = [r.get("result", {}) for r in rows]
        results = [r for r in results if r.get("system") == system]
        # Only questions that carry retrieval metrics count (annotated ones).
        annotated = [r["retrieval_metrics"] for r in results if r.get("retrieval_metrics")]
        latencies = [r["latency_ms"] for r in results if r.get("latency_ms") is not None]

        label = SYSTEM_LABELS.get(system, system)
        numeric[label], display[label] = {}, {}
        for column, key in columns.items():
            values = [m[key] for m in annotated if m.get(key) is not None]
            if values:
                mean = float(np.mean(values))
                low, high = _bootstrap_ci(values)
                numeric[label][column] = mean
                display[label][column] = _format_mean_ci(mean, low, high)
                intervals.append(
                    {
                        "System": label,
                        "Metric": column,
                        "Mean": mean,
                        "Low": low if not np.isnan(low) else mean,
                        "High": high if not np.isnan(high) else mean,
                    }
                )
            else:
                numeric[label][column] = float("nan")
                display[label][column] = "n/a"
        display[label]["Median latency (ms)"] = (
            round(float(np.median(latencies))) if latencies else None
        )
        display[label]["Questions"] = len(results)
        display[label]["Annotated"] = len(annotated)

    return (
        pd.DataFrame.from_dict(numeric, orient="index"),
        pd.DataFrame.from_dict(display, orient="index"),
        pd.DataFrame(intervals),
        k,
    )


def _interval_chart(intervals: pd.DataFrame) -> alt.Chart:
    """One panel per metric: mean (dot) with its 95% interval (bar)."""
    # Precision@k is left out of the chart: it is capped by the number of
    # relevant anchors per question. It stays in the table.
    shown = intervals[~intervals["Metric"].str.startswith("Precision")]
    base = alt.Chart().encode(
        x=alt.X("System:N", sort=None, title=None, axis=alt.Axis(labelAngle=-45, labelOverlap=False)),
        color=alt.Color("System:N", legend=None),
    )
    bars = base.mark_errorbar().encode(
        y=alt.Y("Low:Q", scale=alt.Scale(domain=[0, 1]), title=None), y2="High:Q"
    )
    points = base.mark_point(filled=True, size=70).encode(y="Mean:Q")
    return (
        alt.layer(bars, points)
        .properties(width=150, height=220)
        .facet(column=alt.Column("Metric:N", title=None), data=shown)
    )


def _question_id(row: dict[str, Any]) -> Any:
    result = row.get("result", {})
    for source in (row, result):
        for key in ("question_id", "id"):
            if source.get(key):
                return source[key]
    return None


def _paired_differences(
    payload: dict[str, Any], baseline: str, k: int
) -> pd.DataFrame | None:
    """Per-question metric differences versus a baseline, with bootstrap CIs.

    Returns None when question ids cannot be found, since pairing by position
    would be unreliable.
    """
    per_system: dict[str, dict[Any, dict[str, float]]] = {}
    for row in payload.get("results", []):
        result = row.get("result", {})
        qid = _question_id(row)
        if qid is None:
            return None
        if result.get("retrieval_metrics"):
            per_system.setdefault(result.get("system"), {})[qid] = result[
                "retrieval_metrics"
            ]

    base = per_system.get(baseline)
    if not base:
        return None
    records = []
    for system, metrics_by_q in per_system.items():
        if system == baseline:
            continue
        common = sorted(set(base) & set(metrics_by_q), key=str)
        record: dict[str, Any] = {
            "System": SYSTEM_LABELS.get(system, system),
            "Paired questions": len(common),
        }
        for key, name in {**RANKING_METRICS, COVERAGE_KEY: "Article coverage"}.items():
            suffix = "" if key == COVERAGE_KEY else f"@{k}"
            diffs = [
                metrics_by_q[q][key] - base[q][key]
                for q in common
                if key in metrics_by_q[q] and key in base[q]
            ]
            if diffs:
                low, high = _bootstrap_ci(diffs)
                record[f"Δ {name}{suffix}"] = (
                    f"{np.mean(diffs):+.2f} [{low:+.2f}, {high:+.2f}]"
                )
            else:
                record[f"Δ {name}{suffix}"] = "n/a"
        records.append(record)
    return pd.DataFrame(records)


def _comparison_summary(results: list[dict[str, Any]]) -> pd.DataFrame:
    """Annotation-free comparison: latency, coverage and overlap with the first system."""
    first_ids = {p.get("chunk_id") for p in results[0].get("retrieved_passages", [])}
    rows = []
    for result in results:
        passages = result.get("retrieved_passages", [])
        ids = {p.get("chunk_id") for p in passages}
        union = ids | first_ids
        rows.append(
            {
                "System": SYSTEM_LABELS.get(result["system"], result["system"]),
                "Latency (ms)": round(result.get("latency_ms", 0)),
                "Passages": len(passages),
                "Distinct articles": len({p.get("article_id") for p in passages}),
                "Overlap with first system (Jaccard)": (
                    round(len(ids & first_ids) / len(union), 2) if union else 0.0
                ),
            }
        )
    return pd.DataFrame(rows)


